def empty_ratings() -> dict[str, str]:
    return {level: "" for level in RATING_LEVELS}


def row(
    category: str,
    feature: str,
    topic: str,
    guide: str,
    note_hint: str = "",
) -> dict[str, str]:
    r = {
        "หมวด": category,
        "ฟีเจอร์ที่สกัด": feature,
        "หัวข้อประเมิน": topic,
        "สิ่งที่พิจารณา": guide,
        "หมายเหตุ": note_hint,
    }
    r.update(empty_ratings())
    return r


